"""公文骨架库：15 种法定文种（《党政机关公文处理工作条例》）。

每种骨架给出：标题模板、主送机关行、正文段落序列（含写作提示占位）、
结束语、落款要素。供「新建公文」向导生成带占位符的草稿。
占位符约定：【】为需用户填写内容；（提示）为写作提示段。
"""

from dataclasses import dataclass, field


@dataclass
class Skeleton:
    kind: str                      # 文种名
    title_hint: str                # 标题模板
    recipient: str                 # 主送机关行模板（可为空）
    body: list[str] = field(default_factory=list)   # 段落序列
    closing: str = ""              # 结束语（空串=无独立结束语）
    signature: str = ""            # 落款模板
    note: str = ""                 # 写作提示

    def render(self, **kw) -> str:
        """填充占位符后输出纯文本草稿。kw: title/org/date 等。"""
        def sub(s: str) -> str:
            for k, v in kw.items():
                s = s.replace("{" + k + "}", v)
            return s

        lines: list[str] = []
        if kw.get("title"):
            lines.append(kw["title"])
        elif self.title_hint:
            lines.append(sub(self.title_hint))
        lines.append("")
        if self.recipient:
            lines.append(sub(self.recipient))
        for para in self.body:
            p = sub(para)
            if p:
                lines.append(p)
            else:
                lines.append("")
        if self.closing:
            lines.append(self.closing)
        lines.append("")
        if self.signature:
            lines.append(sub(self.signature))
        return "\n".join(lines)


