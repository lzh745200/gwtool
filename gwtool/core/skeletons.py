"""公文骨架库：12 种军队机关公文文种（《军队机关公文处理工作条例》第八条）。

依据：2017-07-17 解放军报发布《军队机关公文处理工作条例》，2017-10-01 施行，
同时废止 2005-10-02《中国人民解放军机关公文处理条例》。

与《党政机关公文处理工作条例》（15 文种）的差异：
  · 军队设「通令」「指示」，党政无；
  · 党政设「决议」「公报」「公告」「意见」「议案」，军队无；
  · 「命令」在军队条例中不带「（令）」后缀。
"""

from dataclasses import dataclass, field


@dataclass
class Skeleton:
    kind: str                      # 文种名
    title_hint: str                # 标题模板
    recipient: str                 # 主送机关行模板（可为空）
    body: list[str] = field(default_factory=list)   # 段落序列
    closing: str = ""              # 结束语（空串=无独立结束语）
    signature: str = ""            # 落款模板
    note: str = ""                 # 写作提示

    def render(self, **kw) -> str:
        """填充占位符后输出纯文本草稿。kw: title/org/date 等。"""
        def sub(s: str) -> str:
            for k, v in kw.items():
                s = s.replace("{" + k + "}", v)
            return s

        lines: list[str] = []
        if kw.get("title"):
            lines.append(kw["title"])
        elif self.title_hint:
            lines.append(sub(self.title_hint))
        lines.append("")
        if self.recipient:
            lines.append(sub(self.recipient))
        for para in self.body:
            p = sub(para)
            if p:
                lines.append(p)
            else:
                lines.append("")
        if self.closing:
            lines.append(self.closing)
        lines.append("")
        if self.signature:
            lines.append(sub(self.signature))
        return "\n".join(lines)


